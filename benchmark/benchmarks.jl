# PlotlySupply benchmarks (decision D14): load time and time-to-first-figure,
# the cost of building the package image, scaling of the hot paths with the
# problem size, and what a figure keeps of the caller's data. Prints every
# table and writes them, with the machine, Julia version and commit, to
# benchmark/RESULTS.md.
#
#     julia --project=benchmark -e 'using Pkg; Pkg.instantiate()'
#     julia --project=benchmark benchmark/benchmarks.jl [options]
#
# Options:
#   --quick              smaller sizes and fewer calls (minutes, not tens of minutes)
#   --repeats N          fresh processes per TTFX scenario (default 3)
#   --no-electron        skip the png/pdf scenarios (they start Electron)
#   --no-ttfx            skip the TTFX scenarios
#   --no-scaling         skip the scaling and memory benchmarks
#   --precompile-cost    also time a rebuild of the package image (minutes)
#   --baseline DIR       also measure the environment in DIR (e.g. one that
#                        loads an older checkout), interleaved with this one
#   --baseline-note TEXT what the baseline is, for the report
#   --output FILE        write the report here instead of benchmark/RESULTS.md

include(joinpath(@__DIR__, "ttfx.jl"))
include(joinpath(@__DIR__, "scaling.jl"))

const BENCHMARK_ROOT = normpath(joinpath(@__DIR__, ".."))

# Commit of the checkout in `dir` (and whether it has uncommitted changes to
# tracked files); "unknown" when `dir` is not a git checkout or git is missing.
function benchmark_commit(dir::AbstractString)
	try
		commit = readchomp(pipeline(`git -C $dir rev-parse HEAD`; stderr = devnull))
		dirty = !isempty(readchomp(pipeline(`git -C $dir status --porcelain --untracked-files=no`; stderr = devnull)))
		return dirty ? "$(commit) (with uncommitted changes)" : commit
	catch err
		(err isa ProcessFailedException || err isa Base.IOError) || rethrow()
		return "unknown (not a git checkout)"
	end
end

function benchmark_machine()
	cpu = Sys.cpu_info()
	load = Sys.loadavg()
	return (
		cpu = isempty(cpu) ? "unknown" : strip(cpu[1].model),
		cores = Sys.CPU_THREADS,
		memory_gb = Sys.total_memory() / 2^30,
		os = string(Sys.KERNEL, " (", Sys.MACHINE, ")"),
		julia = string(VERSION),
		threads = Threads.nthreads(),
		load = isempty(load) ? "unknown" : join((@sprintf("%.1f", l) for l in load), " / "),
	)
end

# Package image build time and size per environment, each in its own child
# process (`precompile_cost.jl`); returns label => (seconds, megabytes).
function benchmark_precompile_cost(projects; repeats::Integer = 1)
	script = joinpath(@__DIR__, "precompile_cost.jl")
	results = Dict{String, Any}()
	for (label, dir) in projects
		cmd = `$(Base.julia_cmd()) --startup-file=no --project=$(dir) $(script) --repeats $(repeats)`
		out = IOBuffer()
		proc = run(pipeline(ignorestatus(cmd); stdout = out, stderr = out); wait = true)
		text = String(take!(out))
		success(proc) || error("precompile cost of $(label) failed (exit code $(proc.exitcode)):\n$(text)")
		seconds = [parse(Float64, m.captures[1]) for m in eachmatch(r"RESULT compilecache=([-+0-9.eE]+)", text)]
		megabytes = [parse(Float64, m.captures[1]) for m in eachmatch(r"RESULT image_megabytes=([-+0-9.eE]+)", text)]
		isempty(seconds) && error("precompile cost of $(label) reported nothing:\n$(text)")
		results[String(label)] = (seconds = seconds, megabytes = megabytes)
	end
	return results
end

function benchmark_parse_args(args)
	opts = Dict{String, Any}(
		"quick" => false, "ttfx" => true, "scaling" => true, "precompile_cost" => false,
		"output" => joinpath(@__DIR__, "RESULTS.md"), "baseline_note" => "",
	)
	ttfx_args = String[]
	i = 1
	while i <= length(args)
		arg = args[i]
		if arg == "--quick"
			opts["quick"] = true
		elseif arg == "--no-ttfx"
			opts["ttfx"] = false
		elseif arg == "--no-scaling"
			opts["scaling"] = false
		elseif arg == "--precompile-cost"
			opts["precompile_cost"] = true
		elseif arg in ("--output", "--baseline-note") && i < length(args)
			opts[arg == "--output" ? "output" : "baseline_note"] = args[i + 1]
			i += 1
		elseif arg in ("--repeats", "--baseline") && i < length(args)
			push!(ttfx_args, arg, args[i + 1])
			i += 1
		elseif arg == "--no-electron"
			push!(ttfx_args, arg)
		else
			error("benchmarks.jl: unknown argument $(repr(arg))")
		end
		i += 1
	end
	opts["ttfx_opts"] = ttfx_parse_args(ttfx_args)
	return opts
end

function benchmark_main(args)
	opts = benchmark_parse_args(args)
	ttfx_opts = opts["ttfx_opts"]
	projects = ttfx_opts.projects
	labels = [String(first(p)) for p in projects]
	machine = benchmark_machine()
	started = time()
	io = IOBuffer()
	println(io, "# PlotlySupply benchmark results\n")
	println(io, "Generated by `benchmark/benchmarks.jl` $(join(args, " "))\n")
	println(io, "| | |\n|---|---|")
	println(io, "| date (UTC) | ", Libc.strftime("%Y-%m-%d %H:%M", time()), " |")
	println(io, "| commit | ", benchmark_commit(BENCHMARK_ROOT), " |")
	if length(projects) > 1
		baseline_dir = last(projects[1])
		note = isempty(opts["baseline_note"]) ? "" : " ($(opts["baseline_note"]))"
		println(io, "| baseline | `", baseline_dir, "`", note, ", commit ", benchmark_commit(baseline_dir), " |")
	end
	@printf(io, "| machine | %s, %d cores, %.0f GB RAM, %s |\n", machine.cpu, machine.cores, machine.memory_gb, machine.os)
	println(io, "| Julia | ", machine.julia, ", ", machine.threads, " thread(s) |")
	println(io, "| load average at start (1 / 5 / 15 min) | ", machine.load, " |")

	if opts["precompile_cost"]
		@info "benchmarks: rebuilding the package image (precompile cost)"
		cost = benchmark_precompile_cost(projects)
		println(io, "\n## Package image build (precompilation)\n")
		println(io, "| environment | build time (s), each rebuild | image size (MB) |")
		println(io, "|---|---|---:|")
		for label in labels
			c = cost[label]
			println(io, "| ", label, " | ", join((@sprintf("%.1f", s) for s in c.seconds), ", "), " | ",
				isempty(c.megabytes) ? "-" : @sprintf("%.1f", maximum(c.megabytes)), " |")
		end
	end

	if opts["ttfx"]
		@info "benchmarks: time to first figure ($(ttfx_opts.repeats) fresh processes per scenario)"
		order, stats = ttfx_measure(projects; repeats = ttfx_opts.repeats, electron = ttfx_opts.electron)
		println(io, "\n## Load time and time to first figure\n")
		println(io, "Seconds, each run in a fresh Julia process. `first_*` includes compilation; ",
			"`second_*` is the same call again in that process. `split_*` divides a first PNG ",
			"export into the Julia model side, loading ElectronCall, the first export window and ",
			"the render; `*_julia_compile` is the compilation time inside a stage (from `@timed`) ",
			"and `split_first_window_electron_and_page` the rest of the first window: the Electron ",
			"application's start-up and the page load. `second_export_window` opens another export ",
			"window on the running application with all Julia code compiled.\n")
		print(io, ttfx_table(order, stats, labels))
	end

	if opts["scaling"]
		@info "benchmarks: scaling and memory$(opts["quick"] ? " (quick)" : "")"
		println(io, "\n## Scaling and memory (", labels[end], ")\n")
		println(io, "Minimum and maximum time over 2-3 runs after a warm-up run (GC included; the ",
			"spread shows how noisy the minimum is on this machine) and the minimum allocated bytes. ",
			"Exponents are the log-log slope of the minimum time and of the bytes between the two ",
			"largest sizes.\n")
		print(io, scaling_run(; quick = opts["quick"]))
	end
	@printf(io, "\nLoad average at the end: %s. Total benchmark time: %.0f s.\n",
		benchmark_machine().load, time() - started)

	report = String(take!(io))
	print(report)
	open(opts["output"], "w") do file
		write(file, report)
	end
	@info "benchmarks: report written to $(opts["output"])"
	return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
	benchmark_main(ARGS)
end
